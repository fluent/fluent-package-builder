    assert_match "fluentd", shell_output("#{bin}/fluent-gem list")

    port = free_port
    (testpath/"fluentd.conf").write <<~CONF
      <system>
        log_level debug
      </system>
      <source>
        @type forward
        listen 127.0.0.1
        port #{port}
      </source>
      <match test.**>
        @type stdout
      </match>
    CONF

    pid = Process.spawn(bin/"fluentd", "-c", testpath/"fluentd.conf",
                        "-o", testpath/"fluentd.log",
                        out: File::NULL, err: File::NULL, chdir: testpath)
    begin
      waited = 0
      log = ""
      until log.include?("fluentd worker is now running")
        raise "fluentd did not start:\n#{log}" if waited > 60

        sleep 1
        waited += 1
        log = File.read(testpath/"fluentd.log") if File.exist?(testpath/"fluentd.log")
      end

      pipe_output("#{bin}/fluent-cat --host 127.0.0.1 --port #{port} test.hello",
                  %Q({"brew":true}\n))
      sleep 3
    ensure
      Process.kill("TERM", pid)
      Process.wait(pid)
    end

    assert_match(/"brew":true/, File.read(testpath/"fluentd.log"))
  end
