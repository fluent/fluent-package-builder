  # GEM_HOME layout: `libexec` holds a plain gem installation (lib/, gems/,
  # specifications/, bin/); the executables exposed in bin/ are small
  # wrappers that point GEM_HOME/GEM_PATH at it plus a persistent
  # user-gem directory, like the launchd/systemd setups of the deb/rpm
  # packages point at /opt/fluent.
  WRAPPED_COMMANDS = %w[fluentd fluent-gem fluent-cat td].freeze

  def install
    gem_home = libexec
    gem_home.mkpath

    # The cmake policy override is the escape hatch CMake documents for
    # the ancient cmake_minimum_required of the library vendored by the
    # cmetrics gem.
    with_env("CMAKE_POLICY_VERSION_MINIMUM" => "3.5") do
      resources.each do |r|
        # `--local` forbids network access at install time, and
        # `--ignore-dependencies` keeps the gem graph exactly the one the
        # release locked (every dependency is present as another resource,
        # listed dependency-first so native builds can invoke their build
        # dependencies).
        system formula_opt_bin("ruby@3.4")/"gem", "install",
               "--local", "--no-document", "--ignore-dependencies",
               r.cached_download.to_s,
               "--install-dir", gem_home.to_s, "--bindir", (gem_home/"bin").to_s
      end
    end
    oh1 "Installed #{Dir[gem_home/"gems/*"].size} gems into #{gem_home}"

    # `mini_portile` leaves a several-megabyte build scratch tree inside the
    # cmetrics gem. The static libraries it produced are already linked into
    # cmetrics.bundle, and the scratch files embed Homebrew's compiler shim
    # paths, which `brew audit` rightfully objects to.
    Dir.glob("#{gem_home}/gems/cmetrics-*/ext/cmetrics/tmp") do |dir|
      rm_rf dir
    end

    pkgshare.install "LICENSE"
    install_default_config
    install_wrappers
    (var/"fluent/gems").mkpath
    (var/"log/fluent").mkpath
  end

  # A minimal working configuration, equivalent in spirit to the
  # fluent-package/templates/etc/ files the deb/rpm packages install.
  def default_config
    <<~CONF
      <system>
        log_level info
      </system>

      <source>
        @type forward
      </source>

      <match **>
        @type stdout
      </match>
    CONF
  end

  # `etc` is outside the Cellar: this file survives upgrades and is only
  # installed with Homebrew's standard preservation of modified configs.
  def install_default_config
    (buildpath/"fluentd.conf").write(default_config)
    (etc/"fluent").install buildpath/"fluentd.conf"
  end

  # The gem executables of the release (fluentd, fluent-gem, fluent-cat,
  # td, ...) live in the gem home; wrap the four user-facing ones so that
  # they work without any environment setup:
  #
  #   GEM_HOME  a persistent directory under `var` where `fluent-gem
  #             install` puts user plugins (survives brew upgrades)
  #   GEM_PATH  user plugins first, then the packaged gems
  #
  # The binstubs in the gem home carry the `ruby@3.4` shebang written by
  # the gem installer, so no interpreter is picked up from PATH.
  def install_wrappers
    WRAPPED_COMMANDS.each do |name|
      (bin/name).write_env_script opt_prefix/"libexec/bin/#{name}",
                                GEM_HOME: var/"fluent/gems",
                                GEM_PATH: "#{var}/fluent/gems:#{opt_prefix}/libexec"
    end
  end

  # One service per formula, per Homebrew convention; only the fluentd
  # daemon, not the td tool.
  service do
    run [opt_bin/"fluentd", "-c", etc/"fluent/fluentd.conf"]
    keep_alive true
    log_path var/"log/fluent/fluentd.log"
    error_log_path var/"log/fluent/fluentd.log"
    working_dir var/"fluent"
  end

